/** Ocean fallback names by region (lon/lat boxes, first match). */
export function oceanName(lon: number, lat: number): string {
  if (lat < -58) return 'Southern Ocean';
  if (lat > 66) return 'Arctic Ocean';
  // Indian Ocean: between Africa and Australia, south of Asia
  if (lon >= 20 && lon <= 120 && lat < 25 && !(lon > 100 && lat > 0)) return lat < -10 ? 'South Indian Ocean' : 'North Indian Ocean';
  if (lon > 120 && lon <= 147 && lat < -10 && lat > -45) return 'South Indian Ocean';
  // Atlantic: between Americas and Europe/Africa
  const atl = lat >= 0 ? (lon > -100 && lon < 20) : lon > -70 && lon < 20;
  if (atl) return lat >= 0 ? 'North Atlantic' : 'South Atlantic';
  return lat >= 0 ? 'North Pacific' : 'South Pacific';
}

