/** ASCII slug for city keys: "São Paulo" → "sao-paulo". */
export function citySlug(name: string): string {
  return name
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[’'`]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function build(): CitySeed[] {
  const out: CitySeed[] = [];
  for (const [country, rows] of Object.entries(RAW)) {
    for (const [name, lon, lat, pop, flags, tier] of rows) {
      out.push({
        key: `${country}-${citySlug(name)}`,
        name,
        country,
        lonlat: [lon, lat],
        population: pop,
        capital: flags.includes('C'),
        port: flags.includes('P'),
        tier: Math.max(1, Math.min(5, tier)) as CitySeed['tier'],
      });
    }
  }
  return out;
}

