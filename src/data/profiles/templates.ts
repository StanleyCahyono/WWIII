/**
 * Shared profile templates (owner: profiles agent).
 *
 * A template is a starting point: technology seeds, force-recipe densities, facility defaults,
 * reserve depth and a personality. Every final profile then states its own geography and
 * economy through authored city functions, buildings and formations (see the region files).
 *
 * City output table: a city's base output per day =
 *   round(tier × intensity × (BASE + Σ FUNCTION_OUTPUT[f]))  (+ authored `out`)
 * `intensity` is an authoring input only; the final CountryProfile stores plain whole-unit
 * outputs per city and carries no multiplier field.
 */
