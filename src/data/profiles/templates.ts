export interface TemplateDef {
  id: TemplateId;
  label: string;
  description: string;
  intensity: number;
  /** Days of consumption held in the opening reserve. */
  stockDays: number;
  lift: number;
  maint: number;
  techs: TechId[];
  /** Naval techs (dropped for landlocked seats). */
  navalTechs: TechId[];
  /** Force recipe densities per tier point (Σ city tiers) / per port tier point. */
  armyPerTier: number;
  airPerTier: number;
  navyPerPortTier: number;
  /** Fraction of recipe infantry raised as militia. */
  militiaShare: number;
  readiness: number;
  personality: Personality;
  difficulty: 'easy' | 'moderate' | 'hard';
  /** Facility defaults: capital, other cities of tier ≥ 3, ports of tier ≥ 2 (non-landlocked). */
  capitalBuildings: Partial<Record<BuildingTypeId, number>>;
  majorCityBuildings: Partial<Record<BuildingTypeId, number>>;
  portBuildings: Partial<Record<BuildingTypeId, number>>;
}

